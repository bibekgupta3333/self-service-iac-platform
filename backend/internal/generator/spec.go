// Package generator renders the Terraform root module for a stack.
//
// Everything here is pure: a StackSpec goes in, a deterministic set of files comes
// out, and nothing touches the filesystem, network or clock. The Generator struct
// only carries configuration (repository URL and the backend/provider strategies);
// the rendering itself is done by plain functions over immutable values.
package generator

import (
	"bytes"
	"encoding/json"
	"fmt"
	"regexp"
	"slices"
	"strings"

	"github.com/bibekgupta3333/self-service-iac-platform/backend/internal/catalog"
	"github.com/bibekgupta3333/self-service-iac-platform/backend/internal/fp"
	"github.com/bibekgupta3333/self-service-iac-platform/backend/internal/tfname"
)

// Header starts every generated file.
const Header = "# Code generated by the platform. DO NOT EDIT."

// StackSpec is everything needed to render one stack root.
type StackSpec struct {
	Environment        string
	Team               string
	Stack              string
	Region             string
	CostCenter         string // optional; added to default tags
	RequestID          string // short id, e.g. req-7k3p9x
	FencingToken       int64
	TerraformVersion   string // required_version constraint, e.g. "~> 1.13"
	AWSProviderVersion string // e.g. "~> 5.80"
	// Lifecycle is recorded in iacp.stack.json: LifecycleActive (the default) or
	// LifecycleDestroy. A destroy renders no module blocks, so the plan shows every
	// resource of the stack being destroyed (docs/03 §6.4).
	Lifecycle string
	Resources []Resource
	DependsOn []string
}

// Stack lifecycles written to iacp.stack.json.
const (
	LifecycleActive  = "active"
	LifecycleDestroy = "destroy"
)

// lifecycleOf returns the effective lifecycle of s: active unless it says otherwise. Pure.
func (s StackSpec) lifecycleOf() string {
	if s.Lifecycle == "" {
		return LifecycleActive
	}
	return s.Lifecycle
}

// Resource is one module instance in the stack.
type Resource struct {
	Name    string
	Module  string
	Version catalog.SemVer
	GitSHA  string          // commit the version tag resolved to, recorded in iacp.stack.json
	Inputs  json.RawMessage // JSON object; {"$ref": "<instance>.<output>"} values become module references
	Outputs []catalog.Output
}

// StackIdentity is the part of a spec that strategies need.
type StackIdentity struct {
	Environment string
	Team        string
	Stack       string
	Region      string
}

// Identity returns the stack identity of s.
func (s StackSpec) Identity() StackIdentity {
	return StackIdentity{Environment: s.Environment, Team: s.Team, Stack: s.Stack, Region: s.Region}
}

// StateKey is the production-layout state path for the stack (ADR-0009 keeps it for local state too).
func (id StackIdentity) StateKey() string {
	return fmt.Sprintf("%s/%s/%s/terraform.tfstate", id.Environment, id.Team, id.Stack)
}

var (
	nameRe = regexp.MustCompile(`^[a-z][a-z0-9-]{1,40}$`)
	shaRe  = regexp.MustCompile(`^[0-9a-f]{40}$`)
)

// decodedResource is a Resource with its inputs parsed (numbers kept as json.Number).
type decodedResource struct {
	Resource
	inputs map[string]any
}

// prepare validates spec and returns its resources decoded and sorted by name.
func prepare(spec StackSpec) ([]decodedResource, error) {
	switch {
	case !nameRe.MatchString(spec.Environment), !nameRe.MatchString(spec.Team), !nameRe.MatchString(spec.Stack):
		return nil, fmt.Errorf("invalid stack identity %s/%s/%s", spec.Environment, spec.Team, spec.Stack)
	case spec.Region == "":
		return nil, fmt.Errorf("region is required")
	case spec.TerraformVersion == "" || spec.AWSProviderVersion == "":
		return nil, fmt.Errorf("terraform and aws provider version constraints are required")
	case spec.lifecycleOf() != LifecycleActive && spec.lifecycleOf() != LifecycleDestroy:
		return nil, fmt.Errorf("unknown lifecycle %q", spec.Lifecycle)
	case spec.lifecycleOf() == LifecycleDestroy && len(spec.Resources) > 0:
		return nil, fmt.Errorf("a destroy renders no resources, got %d", len(spec.Resources))
	}
	if d := fp.Duplicates(fp.Map(spec.Resources, func(r Resource) string { return r.Name })); len(d) > 0 {
		return nil, fmt.Errorf("duplicate resource names: %v", d)
	}
	byName := map[string]Resource{}
	for _, r := range spec.Resources {
		byName[r.Name] = r
	}
	out := make([]decodedResource, 0, len(spec.Resources))
	for _, r := range spec.Resources {
		if !tfname.IsIdentifier(r.Name) {
			return nil, fmt.Errorf("resource name %q is not an HCL identifier", r.Name)
		}
		if !nameRe.MatchString(r.Module) {
			return nil, fmt.Errorf("resource %s: invalid module name %q", r.Name, r.Module)
		}
		if !shaRe.MatchString(r.GitSHA) {
			return nil, fmt.Errorf("resource %s: module ref must be resolved to a 40-character commit SHA", r.Name)
		}
		inputs, err := decodeInputs(r.Inputs)
		if err != nil {
			return nil, fmt.Errorf("resource %s: %w", r.Name, err)
		}
		if err := checkRefs(inputs, r.Name, byName); err != nil {
			return nil, fmt.Errorf("resource %s: %w", r.Name, err)
		}
		out = append(out, decodedResource{Resource: r, inputs: inputs})
	}
	slices.SortFunc(out, func(a, b decodedResource) int { return strings.Compare(a.Name, b.Name) })
	return out, nil
}

func decodeInputs(raw json.RawMessage) (map[string]any, error) {
	if len(bytes.TrimSpace(raw)) == 0 {
		return map[string]any{}, nil
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	var m map[string]any
	if err := dec.Decode(&m); err != nil {
		return nil, fmt.Errorf("inputs must be a JSON object: %w", err)
	}
	for _, k := range fp.SortedKeys(m) {
		if err := tfname.ValidateInputName(k); err != nil {
			return nil, err
		}
	}
	return m, nil
}

func checkRefs(v any, self string, byName map[string]Resource) error {
	if m, ok := v.(map[string]any); ok {
		if ref, isRef, err := tfname.ParseRef(m); isRef {
			if err != nil {
				return fmt.Errorf("malformed reference: %w", err)
			}
			inst, out := ref.Resource, ref.Output
			target, exists := byName[inst]
			switch {
			case inst == self:
				return fmt.Errorf("reference %s.%s points at itself", inst, out)
			case !exists:
				return fmt.Errorf("reference to unknown resource %q", inst)
			case !slices.ContainsFunc(target.Outputs, func(o catalog.Output) bool { return o.Name == out }):
				return fmt.Errorf("resource %q has no output %q", inst, out)
			}
			return nil
		}
		for _, k := range fp.SortedKeys(m) {
			if err := checkRefs(m[k], self, byName); err != nil {
				return err
			}
		}
	}
	if l, ok := v.([]any); ok {
		for _, e := range l {
			if err := checkRefs(e, self, byName); err != nil {
				return err
			}
		}
	}
	return nil
}
