package publish

import (
	"fmt"
	"slices"
	"strings"
)

// Plan placeholder markers. pr-validate.yml replaces the text between them with the plan
// summary, so the PR body stays the single place reviewers look.
const (
	PlanStart = "<!-- iacp:plan:start -->"
	PlanEnd   = "<!-- iacp:plan:end -->"
)

// PRResource is one module instance listed in the PR body.
type PRResource struct {
	Name    string
	Module  string
	Version string
}

// PRContext is everything the PR title, body, labels and commit message are built from.
type PRContext struct {
	RequestID     string // uuid
	ShortID       string // req-…
	Kind          string // create, update, …
	Environment   string
	Team          string
	Stack         string
	StackPath     string // environments/<env>/<team>/<stack>
	Region        string
	Justification string
	FencingToken  int64
	RequestURL    string // portal link to the request
	Resources     []PRResource
	// Upgrades lists the module versions an upgrade request moves (empty for other kinds).
	Upgrades []PRUpgrade
}

// PRUpgrade is one resource moved to another version of its module by an upgrade.
type PRUpgrade struct {
	Resource string
	Module   string
	From     string
	To       string
	Change   string // patch, minor or major
}

// Title renders the PR title. Pure.
func Title(c PRContext) string {
	return fmt.Sprintf("iacp: %s %s/%s/%s (%s)", c.Kind, c.Environment, c.Team, c.Stack, c.ShortID)
}

// CommitMessage renders the commit message for the generated files. Pure.
func CommitMessage(c PRContext) string {
	return fmt.Sprintf("feat(%s): %s stack %s\n\nRequest: %s\nFencing-Token: %d\n",
		c.Team, c.Kind, c.StackPath, c.ShortID, c.FencingToken)
}

// Labels returns the PR labels, sorted. Pure.
func Labels(c PRContext) []string {
	l := []string{"iacp", "iacp:env:" + c.Environment, "iacp:kind:" + c.Kind, "iacp:team:" + c.Team}
	slices.Sort(l)
	return l
}

// Body renders the PR description: a summary table, the resources, the justification,
// the plan placeholder and the request link. Resources are sorted by name, so the same
// context always renders the same bytes. Pure.
func Body(c PRContext) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## %s\n\n", Title(c))
	b.WriteString("| Field | Value |\n|---|---|\n")
	rows := [][2]string{
		{"Request", fmt.Sprintf("[%s](%s)", c.ShortID, c.RequestURL)},
		{"Kind", c.Kind},
		{"Environment", c.Environment},
		{"Team", c.Team},
		{"Stack", "`" + c.StackPath + "`"},
		{"Region", c.Region},
		{"Fencing token", fmt.Sprintf("%d", c.FencingToken)},
	}
	for _, r := range rows {
		fmt.Fprintf(&b, "| %s | %s |\n", r[0], cell(r[1]))
	}

	res := slices.Clone(c.Resources)
	slices.SortFunc(res, func(a, b PRResource) int { return strings.Compare(a.Name, b.Name) })
	b.WriteString("\n### Resources\n\n| Name | Module | Version |\n|---|---|---|\n")
	for _, r := range res {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", cell(r.Name), cell(r.Module), cell(r.Version))
	}

	if len(c.Upgrades) > 0 {
		writeUpgrades(&b, c.Upgrades)
	}

	if c.Kind == "destroy" {
		b.WriteString("\n> **Destroy.** Merging this change destroys every resource of this stack. " +
			"The generated root holds no modules and is marked `lifecycle: destroy`; review the plan below.\n")
	}

	if j := strings.TrimSpace(c.Justification); j != "" {
		b.WriteString("\n### Justification\n\n")
		for _, line := range strings.Split(escapeHTML(j), "\n") {
			fmt.Fprintf(&b, "> %s\n", strings.TrimRight(line, " \r"))
		}
	}

	b.WriteString("\n### Plan\n\n" + PlanStart + "\n")
	b.WriteString("_Plan pending: `pr-validate.yml` posts the plan, policy and cost summary here._\n")
	b.WriteString(PlanEnd + "\n")

	fmt.Fprintf(&b, "\n---\nGenerated by the self-service IaC platform for [%s](%s). "+
		"Files under `environments/` are generated: change the request, not this branch.\n", c.ShortID, c.RequestURL)
	return b.String()
}

// writeUpgrades renders the upgrade table, sorted by resource, and a warning when one of
// them crosses a major. Pure.
func writeUpgrades(b *strings.Builder, ups []PRUpgrade) {
	ups = slices.Clone(ups)
	slices.SortFunc(ups, func(x, y PRUpgrade) int { return strings.Compare(x.Resource, y.Resource) })
	b.WriteString("\n### Upgrades\n\n| Resource | Module | From | To | Change |\n|---|---|---|---|---|\n")
	major := false
	for _, u := range ups {
		fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s |\n", cell(u.Resource), cell(u.Module), cell(u.From), cell(u.To), cell(u.Change))
		major = major || u.Change == "major"
	}
	if major {
		b.WriteString("\n> **Major upgrade.** Read the module's migration notes before approving, and check that the " +
			"plan below updates in place: a `delete` or `replace` of a stateful resource needs the module owners.\n")
	}
}

// escapeHTML neutralises markup in user text so it cannot fake the plan markers or
// inject HTML into the PR body.
func escapeHTML(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
}

// cell makes a value safe inside a markdown table cell.
func cell(s string) string {
	return strings.NewReplacer("|", "\\|", "\n", " ", "\r", "").Replace(escapeHTML(s))
}
