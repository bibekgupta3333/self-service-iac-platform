"""Provider floors: run a module's offline ``terraform test`` suite on the oldest provider it allows.

A module declares ``aws >= 5.70, < 6.0``. Every CI run resolves the newest 5.x, so the
floor (5.70.0) is never exercised and a resource argument added in 5.80 could slip in
unnoticed. ``stage_module`` copies a module to a scratch directory and adds a Terraform
*override file* that pins each provider with a floor to exactly that version. Terraform
merges override files over the module's own ``required_providers``, so
``terraform init -upgrade`` then selects the floor.

``floor_pins`` and ``render_override`` are pure. ``ModuleStager`` is the only I/O.
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Mapping

from tools.module_release.diffing import constraint_floor
from tools.module_release.interface import parse_interface

OVERRIDE_FILE = "provider_floor_override.tf"
# Directories that are not part of the module source and would only cost disk.
_SKIPPED = shutil.ignore_patterns(".terraform", ".terraform.lock.hcl", "*.tfstate", "*.tfstate.backup", "examples")


class FloorError(ValueError):
    """A provider constraint has no readable floor, or the module has none to test."""


@dataclass(frozen=True)
class FloorPin:
    """One provider pinned to the lowest version its constraint allows."""

    local_name: str
    source: str
    version: str

    def render(self) -> str:
        return (
            f"    {self.local_name} = {{\n"
            f'      source  = "{self.source}"\n'
            f'      version = "= {self.version}"\n'
            "    }\n"
        )


def floor_pins(providers: Mapping[str, str | None]) -> tuple[FloorPin, ...]:
    """A pin for every provider whose constraint sets a lower bound, sorted by source. Pure.

    ``providers`` maps source to constraint, as ``parse_interface`` returns it. A
    provider without a lower bound (floor 0.0.0) has nothing to pin and is skipped.
    """
    pins = []
    for source, constraint in sorted(providers.items()):
        floor = constraint_floor(constraint)
        if floor is None:
            raise FloorError(f"cannot read the floor of {source} {constraint!r}")
        if floor == (0, 0, 0):
            continue
        pins.append(FloorPin(source.rsplit("/", 1)[-1], source, ".".join(map(str, floor))))
    return tuple(pins)


def render_override(pins: tuple[FloorPin, ...]) -> str:
    """The override file that pins ``pins``. Pure."""
    if not pins:
        raise FloorError("no provider with a lower bound to pin")
    body = "".join(pin.render() for pin in pins)
    return (
        "# Generated by tools.provider_floor: pins each provider to its declared floor.\n"
        "terraform {\n  required_providers {\n" + body + "  }\n}\n"
    )


_LOCK_RE = re.compile(r'provider\s+"registry\.terraform\.io/([^"]+)"\s*\{[^}]*?\bversion\s*=\s*"([^"]+)"', re.S)


def locked_versions(lock_text: str) -> dict[str, str]:
    """Provider source -> selected version, from the text of a ``.terraform.lock.hcl``. Pure."""
    return {source: version for source, version in _LOCK_RE.findall(lock_text)}


def floor_mismatches(pins: tuple[FloorPin, ...], locked: dict[str, str]) -> tuple[str, ...]:
    """One message per pin whose provider was not resolved to exactly its floor. Pure."""
    return tuple(
        f"{pin.source}: expected the floor {pin.version}, init selected {locked.get(pin.source, 'nothing')}"
        for pin in pins
        if locked.get(pin.source) != pin.version
    )


class ModuleStager:
    """Copies a module to a scratch directory and writes the floor override there."""

    def stage(self, module_dir: Path, dest: Path) -> tuple[FloorPin, ...]:
        if not module_dir.is_dir():
            raise FloorError(f"{module_dir} is not a directory")
        if dest.exists() and any(dest.iterdir()):
            raise FloorError(f"{dest} is not empty")
        files = {p.name: p.read_text(encoding="utf-8") for p in module_dir.glob("*.tf")}
        pins = floor_pins(parse_interface(files).providers)
        override = render_override(pins)
        shutil.copytree(module_dir, dest, ignore=_SKIPPED, dirs_exist_ok=True)
        (dest / OVERRIDE_FILE).write_text(override, encoding="utf-8")
        return pins

    def verify(self, staged_dir: Path) -> tuple[str, ...]:
        """Problems with a staged module after ``terraform init -upgrade``: the lock file must pin every floor."""
        lock = staged_dir / ".terraform.lock.hcl"
        if not lock.is_file():
            raise FloorError(f"{lock} is missing: run terraform init first")
        files = {p.name: p.read_text(encoding="utf-8") for p in staged_dir.glob("*.tf")}
        if OVERRIDE_FILE not in files:
            raise FloorError(f"{staged_dir} was not staged by tools.provider_floor")
        pins = floor_pins(parse_interface(files).providers)
        return floor_mismatches(pins, locked_versions(lock.read_text(encoding="utf-8")))
